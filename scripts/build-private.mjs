// Bundles /private/*.html into src/api/_private/pages.js so the /api/private
// function can serve them without reading from disk at runtime (the HTML is
// never placed in the public output folder).
//
// Run after editing anything in /private:  npm run build:private

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const srcDir = join(root, 'private');
const outFile = join(root, 'src', 'api', '_private', 'pages.js');

const pages = {};
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.html')).sort()) {
  pages[basename(file, '.html')] = readFileSync(join(srcDir, file), 'utf8');
}

const body = Object.entries(pages)
  .map(([name, html]) => `  ${JSON.stringify(name)}: ${JSON.stringify(html)},`)
  .join('\n');

writeFileSync(
  outFile,
  `// GENERATED by scripts/build-private.mjs from /private/*.html — do not edit.\nexport default {\n${body}\n};\n`
);
console.log(`Bundled ${Object.keys(pages).length} private page(s): ${Object.keys(pages).join(', ')}`);
